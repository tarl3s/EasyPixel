#!/usr/bin/env bash
# Rewrites src/EasyPixel/Lang/en.json from the app's sources: every L.T("…") / L.F("…") literal and every
# {loc:T '…'} in XAML, plus the names the UI shows through L.T at run time (tool names, file format names).
# The UI test Lang_EnJsonHasEveryText fails when this needs running.
set -euo pipefail
cd "$(dirname "$0")/../src"
find EasyPixel EasyPixel.Core/Formats -type f \( -name '*.cs' -o -name '*.axaml' \) -not -path '*/obj/*' -not -path '*/bin/*' -print0 |
  xargs -0 perl -ne '
    while (/L\.[TF]\("((?:[^"\\]|\\.)*)"/g) { $k{$1} = 1 }
    while (/loc:T \x27([^\x27]*)\x27/g) { $k{$1} = 1 }
    if ($ARGV =~ m{/Tools/}) { while (/(?:Tool\(ToolKind\.\w+|base\(ToolKind\.\w+|=> ToolKind\.\w+ =>|_ =>), "([^"]+)"/g) { $k{$1} = 1 }
                               while (/(?:ToolKind\.\w+ => |_ => )"([^"]+)"/g) { $k{$1} = 1 } }
    if ($ARGV =~ m{/Formats/}) { while (/public string Name => "([^"]+)"/g) { $k{$1} = 1 } }
    END {
      print "{\n  \"_note\": \"English UI texts (keys = values). Generated by tools/Update-Strings.sh; other languages translate these keys.\",\n";
      print join(",\n", map { "  \"$_\": \"$_\"" } sort keys %k), "\n}\n";
    }' > EasyPixel/Lang/en.json
echo "en.json: $(grep -c '": "' EasyPixel/Lang/en.json) lines"
